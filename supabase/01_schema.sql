-- ── Developer check ─────────────────────────────────────────────────────────
CREATE FUNCTION is_developer() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.app_admins
    WHERE lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- ── Option helpers (used by the Customize screen) ───────────────────────────
-- Which table columns store values of each option list.
CREATE FUNCTION option_refs(p_kind text)
RETURNS TABLE (tbl text, col text, is_array boolean)
LANGUAGE sql IMMUTABLE AS $$
  SELECT v.tbl, v.col, v.is_array FROM (VALUES
    ('stage',           'tasks',         'stage',      false),
    ('priority',        'tasks',         'priority',   false),
    ('department',      'tasks',         'department', false),
    ('department',      'employees',     'department', false),
    ('task_type',       'tasks',         'task_type',  false),
    ('brief_type',      'briefs',        'brief_type', false),
    ('brief_status',    'briefs',        'status',     false),
    ('client_tier',     'clients',       'tier',       false),
    ('client_status',   'clients',       'status',     false),
    ('industry',        'clients',       'industry',   false),
    ('platform',        'clients',       'platforms',  true),
    ('campaign_status', 'ad_campaigns',  'status',     false)
  ) AS v(kind, tbl, col, is_array)
  WHERE v.kind = p_kind;
$$;

CREATE FUNCTION option_usage(p_kind text, p_value text) RETURNS integer
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE r record; n integer := 0; c integer;
BEGIN
  FOR r IN SELECT * FROM option_refs(p_kind) LOOP
    IF r.is_array THEN
      EXECUTE format('SELECT count(*) FROM public.%I WHERE %L = ANY(%I)', r.tbl, p_value, r.col) INTO c;
    ELSE
      EXECUTE format('SELECT count(*) FROM public.%I WHERE %I = %L', r.tbl, r.col, p_value) INTO c;
    END IF;
    n := n + c;
  END LOOP;
  RETURN n;
END $$;

-- Rename an option everywhere it is used (records, option list, bounce-stage setting).
CREATE FUNCTION rename_option(p_kind text, p_old text, p_new text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE r record;
BEGIN
  IF NOT is_developer() THEN RAISE EXCEPTION 'Only the developer account can change options'; END IF;
  p_new := btrim(p_new);
  IF p_new = '' THEN RAISE EXCEPTION 'Name cannot be empty'; END IF;
  IF EXISTS (SELECT 1 FROM config_options WHERE kind = p_kind AND value = p_new) THEN
    RAISE EXCEPTION '"%" already exists in this list', p_new;
  END IF;
  UPDATE config_options SET value = p_new WHERE kind = p_kind AND value = p_old;
  FOR r IN SELECT * FROM option_refs(p_kind) LOOP
    IF r.is_array THEN
      EXECUTE format('UPDATE public.%I SET %I = array_replace(%I, %L, %L) WHERE %L = ANY(%I)',
                     r.tbl, r.col, r.col, p_old, p_new, p_old, r.col);
    ELSE
      EXECUTE format('UPDATE public.%I SET %I = %L WHERE %I = %L', r.tbl, r.col, p_new, r.col, p_old);
    END IF;
  END LOOP;
  IF p_kind = 'stage' THEN
    UPDATE workspace_settings SET value = to_jsonb(p_new) WHERE key = 'bounce_stage' AND value = to_jsonb(p_old);
  END IF;
END $$;

-- Delete an option; records that used it move to p_replacement (or become empty).
CREATE FUNCTION delete_option(p_kind text, p_value text, p_replacement text DEFAULT NULL) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE r record;
BEGIN
  IF NOT is_developer() THEN RAISE EXCEPTION 'Only the developer account can change options'; END IF;
  IF p_replacement IS NOT NULL AND NOT EXISTS (SELECT 1 FROM config_options WHERE kind = p_kind AND value = p_replacement) THEN
    RAISE EXCEPTION 'Replacement "%" does not exist', p_replacement;
  END IF;
  FOR r IN SELECT * FROM option_refs(p_kind) LOOP
    IF r.is_array THEN
      IF p_replacement IS NULL THEN
        EXECUTE format('UPDATE public.%I SET %I = array_remove(%I, %L) WHERE %L = ANY(%I)',
                       r.tbl, r.col, r.col, p_value, p_value, r.col);
      ELSE  -- replace, then drop duplicates while keeping order
        EXECUTE format($f$UPDATE public.%1$I SET %2$I = COALESCE((
                           SELECT array_agg(x ORDER BY o) FROM (
                             SELECT x, min(o) AS o FROM unnest(array_replace(%2$I, %3$L, %4$L)) WITH ORDINALITY AS t(x, o) GROUP BY x
                           ) s), '{}') WHERE %3$L = ANY(%2$I)$f$,
                       r.tbl, r.col, p_value, p_replacement);
      END IF;
    ELSE
      EXECUTE format('UPDATE public.%I SET %I = %L WHERE %I = %L', r.tbl, r.col, p_replacement, r.col, p_value);
    END IF;
  END LOOP;
  DELETE FROM config_options WHERE kind = p_kind AND value = p_value;
  IF p_kind = 'stage' THEN
    DELETE FROM workspace_settings WHERE key = 'bounce_stage' AND value = to_jsonb(p_value);
  END IF;
END $$;

