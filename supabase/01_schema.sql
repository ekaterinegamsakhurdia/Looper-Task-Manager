-- ── Core tables ─────────────────────────────────────────────────────────────
-- Stage / priority / department / status columns are plain TEXT on purpose: the
-- allowed values live in config_options so the developer can add, rename, recolor,
-- reorder and remove them from the app without touching SQL.

CREATE TABLE employees (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  full_name   text NOT NULL,
  email       text UNIQUE NOT NULL,
  role        text,
  department  text,
  avatar_url  text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE clients (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  num          bigint GENERATED ALWAYS AS IDENTITY,
  name         text NOT NULL,
  industry     text,
  tier         text,
  status       text DEFAULT 'Active',
  platforms    text[] NOT NULL DEFAULT '{}',
  am_owner_id  uuid REFERENCES employees(id) ON DELETE SET NULL,
  notes        text,
  custom       jsonb NOT NULL DEFAULT '{}',
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

-- One row per running ad campaign (Ad Ops). Report status is derived in the app
-- from last_reported (threshold = workspace setting report_due_days).
CREATE TABLE ad_campaigns (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text NOT NULL,
  client_id      uuid NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  am_owner_ids   uuid[] NOT NULL DEFAULT '{}',
  advertiser_ids uuid[] NOT NULL DEFAULT '{}',
  status         text DEFAULT 'Awaiting Tasks',
  start_date     date,
  end_date       date,
  budget         numeric(12,2),
  last_reported  date,
  notes          text,
  custom         jsonb NOT NULL DEFAULT '{}',
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE briefs (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title                text NOT NULL,
  client_id            uuid NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  campaign_id          bigint REFERENCES ad_campaigns(id) ON DELETE SET NULL,
  am_owner_id          uuid REFERENCES employees(id) ON DELETE SET NULL,
  copywriter_id        uuid REFERENCES employees(id) ON DELETE SET NULL,
  status               text DEFAULT 'Copy',
  brief_type           text,
  content              text,
  committed_task_count int NOT NULL DEFAULT 0,
  custom               jsonb NOT NULL DEFAULT '{}',
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tasks (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title           text NOT NULL,
  brief_id        uuid REFERENCES briefs(id) ON DELETE SET NULL,
  client_id       uuid REFERENCES clients(id) ON DELETE SET NULL,
  campaign_id     bigint REFERENCES ad_campaigns(id) ON DELETE SET NULL,
  stage           text DEFAULT 'Not started',
  priority        text DEFAULT 'P3',
  department      text,
  task_type       text,
  assigned_to     uuid[] NOT NULL DEFAULT '{}',
  deadline        date,
  bounce_internal boolean NOT NULL DEFAULT false,
  bounce_client   boolean NOT NULL DEFAULT false,
  rev_internal    int NOT NULL DEFAULT 0,
  rev_client      int NOT NULL DEFAULT 0,
  notes           text,
  custom          jsonb NOT NULL DEFAULT '{}',
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
